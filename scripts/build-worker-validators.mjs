// Precompile the C-16 validator for the Worker (R-705). Workers forbid runtime code generation
// (`new Function`), so ajv cannot compile there; ajv standalone emits the validator as plain ESM.
// One entry per shipped major (schemaVersion): the endpoint accepts every major it has ever
// shipped (ALPHA-CONTRACTS § C-16). A new major adds a pinned schema copy + a line in MAJORS.
//   node scripts/build-worker-validators.mjs          write worker/c16-validators.generated.js
//   node scripts/build-worker-validators.mjs --check  exit 1 if the committed file is stale
import { readFileSync, writeFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = new URL('../', import.meta.url);
const OUT = new URL('worker/c16-validators.generated.js', root);
const MAJORS = { validateV1: 'contracts/c16-feedback.schema.json' };

export function generate() {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: false,
    validateFormats: true,
    code: { source: true, esm: true, lines: true },
  });
  addFormats(ajv);
  const refs = {};
  for (const [name, path] of Object.entries(MAJORS)) {
    const schema = JSON.parse(readFileSync(new URL(path, root), 'utf8'));
    ajv.addSchema(schema, `${name}:${schema.$id}`);
    refs[name] = `${name}:${schema.$id}`;
  }
  const header =
    '// GENERATED by scripts/build-worker-validators.mjs from contracts/c16-feedback.schema.json.\n' +
    '// Do not edit; run `npm run generate:worker`. tests/feedback-endpoint.test.ts checks it is fresh.\n';
  // ajv standalone still emits CommonJS `require(...)` for two runtime helpers even in esm mode;
  // rewrite them to one ESM import + an inlined ucs2length so the module loads in Workers,
  // vitest and esbuild alike. Any other `require(` is a generator failure, never shipped.
  let code = standaloneCode(ajv, refs)
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length')
    .replaceAll('require("ajv-formats/dist/formats").fullFormats', 'fullFormats');
  if (code.includes('require(')) throw new Error('unexpected require() in standalone validator');
  code = code.replace('"use strict";\n', '');
  return header + PRELUDE + code;
}

const PRELUDE = `import { fullFormats } from 'ajv-formats/dist/formats.js';
// ajv/dist/runtime/ucs2length: maxLength counts code points, as the client-side ajv does.
function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length++;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos++;
  }
  return length;
}
`;

const isMain = process.argv[1] && new URL(`file://${process.argv[1]}`).href === import.meta.url;
if (isMain) {
  const code = generate();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8');
    if (current !== code) {
      console.error('worker/c16-validators.generated.js is stale: run npm run generate:worker');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, code);
  }
}
