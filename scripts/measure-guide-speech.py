#!/usr/bin/env python3
"""Measure where speech really ends inside every recorded guide range of a delivery file.
Decodes each delivered Opus, takes 10 ms RMS frames, and marks a frame active when it exceeds 5% of the
clip's own 95th-percentile energy. Speech runs are joined across gaps under 0.15 s, and the run that
reaches the range end is followed past it. Also records tailRoomSeconds: the silence after the range end before the next speech (minus 0.06 s, at most 0.5 s) that the player may keep playing. Usage: measure-guide-speech.py <delivery.json> <out.json>"""
import json,subprocess,sys,tempfile,os,wave,urllib.request
import numpy as np
d=json.load(open(sys.argv[1]));out={'method':'rms10ms>5%p95,join<0.15s,follow past range end up to next clip start','sources':{}}
tmp=tempfile.mkdtemp();cache={}
def audio(url):
    if url in cache:return cache[url]
    f=os.path.join(tmp,'a%d.opus'%len(cache));urllib.request.urlretrieve(url,f);w=f+'.wav'
    subprocess.run(['ffmpeg','-v','error','-y','-i',f,'-ac','1','-ar','16000',w],check=True)
    x=wave.open(w);s=np.frombuffer(x.readframes(x.getnframes()),dtype='<i2').astype(float)/32768
    n=len(s)//160;e=np.sqrt((s[:n*160].reshape(n,160)**2).mean(1));cache[url]=e;return e
starts={}
for en in d['entries']:
    if en['path'].startswith('/audio/source/') and 'playbackRange' in en and 'audioReplacement' in en:starts.setdefault(en['source']['sha256'],[]).append(en['playbackRange']['startSeconds'])
for en in d['entries']:
    if not en['path'].startswith('/audio/source/') or 'playbackRange' not in en or 'audioReplacement' not in en:continue
    e=audio(en['delivery']['url']);r=en['playbackRange'];a,b=int(r['startSeconds']*100),int(r['endSeconds']*100)
    pk=np.percentile(e[a:b],95);act=e>0.05*pk;idx=np.where(act[a:b])[0]
    if len(idx)==0:continue
    first=a+idx[0];last=a+idx[-1]
    j=last+1
    nxt=[int(x*100) for x in starts[en['source']['sha256']] if x>=r['endSeconds']-1e-9];cap=min(nxt) if nxt else len(e)
    while j<cap and act[j:j+15].any():
        j+=1;last=j-1 if act[j-1] else last
    last=min(last,cap-1)
    k=a+idx[0]
    end=last+1;f=end
    while f<len(e) and not act[f:f+3].all():f+=1
    room=0.5 if f>=len(e) else min(0.5,max(0.0,f/100-0.06-r['endSeconds']))
    out['sources'].setdefault(en['source']['sha256'],{})[en['path']]={'speechStartSeconds':first/100,'speechEndSeconds':end/100,'tailRoomSeconds':int(room*100+1e-9)/100,'nextSpeechStartSeconds':None if f>=len(e) else f/100}
open(sys.argv[2],'w').write('// Generated by scripts/measure-guide-speech.py from the delivered audio; do not edit.\nexport const guideSpeech = '+json.dumps(out,indent=1,sort_keys=True)+';\n')
